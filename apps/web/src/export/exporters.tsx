import type { ReactElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import type { Diagram } from "@linework/shared";
import { chartDrawing } from "../charts/ChartSvg";
import { DiagramContent, visibleNodesInOrder } from "../render/DiagramSvg";
import { embeddedFontCss } from "./fonts";
import { contentBounds } from "../flowchart/model";

const EXPORT_PADDING = 32;

export interface SvgOptions {
  /** CSS placed in the SVG, typically @font-face rules with embedded fonts. */
  readonly css?: string;
}

function StyleTag({ css }: { css: string | undefined }): ReactElement | null {
  // dangerouslySetInnerHTML keeps CSS quotes intact; the content is generated by us, never user input.
  return css ? <style dangerouslySetInnerHTML={{ __html: css }} /> : null;
}

/** Standalone SVG document for the whole diagram, cropped to its content. */
export function diagramToSvg(
  diagram: Diagram,
  options: SvgOptions = {},
): { svg: string; width: number; height: number } {
  const chart = chartDrawing(diagram);
  if (chart) {
    const { width, height } = chart;
    const markup = renderToStaticMarkup(
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={width}
        height={height}
        viewBox={`0 0 ${String(width)} ${String(height)}`}
      >
        <StyleTag css={options.css} />
        {chart.content}
      </svg>,
    );
    return { svg: `<?xml version="1.0" encoding="UTF-8"?>\n${markup}`, width, height };
  }
  const bounds = contentBounds(diagram, visibleNodesInOrder(diagram)) ?? {
    x: 0,
    y: 0,
    width: 200,
    height: 120,
  };
  const x = bounds.x - EXPORT_PADDING;
  const y = bounds.y - EXPORT_PADDING;
  const width = Math.ceil(bounds.width + EXPORT_PADDING * 2);
  const height = Math.ceil(bounds.height + EXPORT_PADDING * 2);
  const markup = renderToStaticMarkup(
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={width}
      height={height}
      viewBox={`${String(x)} ${String(y)} ${String(width)} ${String(height)}`}
    >
      <StyleTag css={options.css} />
      {diagram.background !== "transparent" && (
        <rect x={x} y={y} width={width} height={height} fill={diagram.background} />
      )}
      <DiagramContent diagram={diagram} />
    </svg>,
  );
  return { svg: `<?xml version="1.0" encoding="UTF-8"?>\n${markup}`, width, height };
}

/** SVG with the style's fonts embedded, for files and images that leave the app. */
export async function diagramToPortableSvg(
  diagram: Diagram,
): Promise<{ svg: string; width: number; height: number }> {
  let css: string | undefined;
  try {
    css = await embeddedFontCss(diagram.styleId);
  } catch {
    // Offline or blocked: export with system fallback fonts rather than failing.
    css = undefined;
  }
  return diagramToSvg(diagram, css ? { css } : {});
}

export async function diagramToPng(diagram: Diagram, scale = 2): Promise<Blob> {
  const { svg, width, height } = await diagramToPortableSvg(diagram);
  const url = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
  try {
    const image = new Image();
    image.decoding = "async";
    image.src = url;
    await image.decode();
    const canvas = document.createElement("canvas");
    canvas.width = Math.round(width * scale);
    canvas.height = Math.round(height * scale);
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("Canvas 2D context unavailable");
    ctx.scale(scale, scale);
    ctx.drawImage(image, 0, 0, width, height);
    return await new Promise<Blob>((resolve, reject) => {
      canvas.toBlob((blob) => {
        if (blob) resolve(blob);
        else reject(new Error("PNG encoding failed"));
      }, "image/png");
    });
  } finally {
    URL.revokeObjectURL(url);
  }
}

export function diagramToJson(diagram: Diagram): string {
  return JSON.stringify(diagram, null, 2);
}

export function safeFileName(title: string): string {
  const cleaned = title
    .trim()
    .replace(/[^a-z0-9-_ ]+/gi, "")
    .replace(/\s+/g, "-")
    .toLowerCase();
  return cleaned || "diagram";
}

export function downloadBlob(blob: Blob, fileName: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = fileName;
  document.body.append(link);
  link.click();
  link.remove();
  // Give the browser a tick to start the download before revoking.
  setTimeout(() => {
    URL.revokeObjectURL(url);
  }, 1000);
}

/** Copies the diagram to the clipboard as a PNG image, for pasting into docs and chat. */
export async function copyPngToClipboard(diagram: Diagram): Promise<void> {
  if (typeof ClipboardItem === "undefined") throw new Error("This browser can't copy images");
  // Pass a promise so Safari keeps the user-gesture permission while the PNG renders.
  await navigator.clipboard.write([new ClipboardItem({ "image/png": diagramToPng(diagram) })]);
}

/** Copies standalone SVG markup as text. */
export async function copySvgToClipboard(diagram: Diagram): Promise<void> {
  const { svg } = await diagramToPortableSvg(diagram);
  await navigator.clipboard.writeText(svg);
}

/**
 * Opens the browser's print dialog with just the diagram, sized to fit one page, so
 * "Save as PDF" produces a vector PDF without a server or a PDF library.
 */
export async function printDiagram(diagram: Diagram): Promise<void> {
  const { svg, width, height } = await diagramToPortableSvg(diagram);
  const landscape = width > height;
  const title = diagram.title.replaceAll("&", "&amp;").replaceAll("<", "&lt;");
  const frame = document.createElement("iframe");
  frame.setAttribute("aria-hidden", "true");
  frame.style.cssText = "position:fixed;right:0;bottom:0;width:0;height:0;border:0;visibility:hidden";
  frame.srcdoc =
    `<!doctype html><html><head><meta charset="utf-8"><title>${title}</title><style>` +
    `@page{size:${landscape ? "landscape" : "portrait"};margin:12mm}` +
    "html,body{margin:0;height:100%}body{display:flex;align-items:center;justify-content:center}" +
    "svg{max-width:100%;max-height:100%;width:auto;height:auto}" +
    `</style></head><body>${svg.replace(/^<\?xml[^>]*>\s*/, "")}</body></html>`;
  const loaded = new Promise((resolve) => {
    frame.addEventListener("load", resolve, { once: true });
  });
  document.body.append(frame);
  await loaded;
  const win = frame.contentWindow;
  if (!win) {
    frame.remove();
    throw new Error("Printing is not available");
  }
  win.focus();
  win.print();
  // Remove after the dialog closes (print() blocks in most browsers; the delay covers the rest).
  setTimeout(() => {
    frame.remove();
  }, 1000);
}
